package ua.studyplanner.prediction.domain;

public enum PredictionMethod {
    /** Початкова оцінка користувача, без навчання чи коригування. */
    USER_ESTIMATE,
    /** Гребенева регресія, навчена на історії виконаних задач користувача. */
    REGRESSION,
    /** Власна оцінка користувача, скоригована середнім відхиленням фактичного часу від оцінок. */
    ESTIMATE_ADJUSTED,
    /** Медіана фактичного часу виконаних задач, коли оцінки немає. */
    HISTORY_MEDIAN
}
